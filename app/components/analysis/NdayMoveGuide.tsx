      <p>
        「過去 n 営業日で p% 以上下げた（上げた）」という条件が成り立った後に何が起きたかを、3つの別々の問いに分けて調べます。
        ①<b>分布</b>：条件成立日を0日目として、その後 H 営業日の終値がどう動いたか（後から分かった値動きの記述）。
        ②<b>実行可能な売買</b>：条件成立日の引けで判定し、翌営業日の寄りで買い、h 日目の引けで売る規則を、当時の情報だけで実行した成績。
        ③<b>頑健性</b>：n・p・h を変えた候補の全件、年代順のウォークフォワード、CSCV による過剰適合確率 PBO で、②の成績が偶然や選び過ぎで説明できないかの点検。
      </p>
      <p>
