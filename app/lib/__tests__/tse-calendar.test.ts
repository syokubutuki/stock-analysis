function* weekdays(fromISO: string, toISO: string): Generator<string> {
  const d = new Date(`${fromISO}T00:00:00Z`);
  const end = new Date(`${toISO}T00:00:00Z`);
  for (; d <= end; d.setUTCDate(d.getUTCDate() + 1)) {
    const dow = d.getUTCDay();
    if (dow !== 0 && dow !== 6) yield d.toISOString().slice(0, 10);
  }
}

describe("tseClosureReason: 配信データから観測した休場日と一致する", () => {
  test("2016-10〜2026-09 の平日について、休場日の集合が観測と過不足なく一致する", () => {
    const computed = [...weekdays("2016-10-03", "2026-09-30")].filter(
      (t) => tseClosureReason(t) !== null,
    );
    assert.equal(OBSERVED_WEEKDAY_CLOSURES.length, 169);
    assert.deepEqual(computed, OBSERVED_WEEKDAY_CLOSURES);
  });
});

describe("tseClosureReason: 規則と特例", () => {
  test("振替休日・国民の休日・年末年始・特例の祝日に名前を付ける", () => {
    assert.deepEqual(
      [
        "2018-12-24", // 天皇誕生日(12/23 日曜)の振替
        "2019-04-30", // 4/29 と 5/1 に挟まれた国民の休日
        "2019-05-01", // 即位の日（特例）
        "2019-05-06", // 5/5 日曜の振替（5/3・5/4 を飛ばした先）
        "2019-10-22", // 即位礼正殿の儀（特例）
        "2020-07-24", // 五輪特措法で移動したスポーツの日
        "2020-10-01", // arrowhead 障害の終日売買停止（祝日ではない休場）
        "2026-09-22", // 敬老の日と秋分の日に挟まれた国民の休日
        "2018-12-31",
        "2019-01-02",
        "2019-01-03",
      ].map(tseClosureReason),
      [
        "振替休日",
        "国民の休日",
        "即位の日",
        "振替休日",
        "即位礼正殿の儀",
        "スポーツの日",
        "終日売買停止（arrowhead 障害）",
        "国民の休日",
        "年末年始休業",
        "年末年始休業",
        "年末年始休業",
      ],
    );
  });

  test("五輪の年は通常の日付が立会日に戻る", () => {
    // 2020 年は海の日・スポーツの日・山の日が移動したので、本来の日付は立会日。
    for (const t of ["2020-07-20", "2020-08-11", "2020-10-12", "2021-07-19", "2021-08-11", "2021-10-11"]) {
      assert.equal(tseClosureReason(t), null, t);
    }
  });

  test("天皇誕生日は 2018 年まで 12/23・2019 年は無し・2020 年以降は 2/23", () => {
    assert.equal(tseClosureReason("2016-12-23"), "天皇誕生日");
    assert.equal(tseClosureReason("2019-12-23"), null);
    assert.equal(tseClosureReason("2019-02-25"), null);
    assert.equal(tseClosureReason("2021-02-23"), "天皇誕生日");
  });

  test("週末は休場・範囲外の年と不正な表記は判定しない（保守側）", () => {
    assert.equal(tseClosureReason("2018-07-14"), "土曜日");
    assert.equal(tseClosureReason("2018-07-15"), "日曜日");
    assert.equal(tseClosureReason("1999-01-01"), null);
    assert.equal(tseClosureReason("2100-01-01"), null);
    assert.equal(tseClosureReason("2018/07/16"), null);
  });
});

describe("followsTseCalendar", () => {
  test("東証の株式・ETF と東証指数だけを対象にする", () => {
    assert.deepEqual(
      ["8306.T", "1306.t", "^N225", "^TPX"].map(followsTseCalendar),
      [true, true, true, true],
    );
    // 投信（基準価額）・米国・為替・金利・日経以外の指数は東証が休みでも正当な値を持ちうる。
    assert.deepEqual(
      ["0331418A", "^GSPC", "AAPL", "USDJPY=X", "^TNX", "^VIX"].map(followsTseCalendar),
      [false, false, false, false, false, false],
    );
  });
});
